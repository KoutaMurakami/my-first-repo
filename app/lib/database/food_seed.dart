class FoodSeed {
  const FoodSeed(
    this.name,
    this.servingLabel,
    this.servingG,
    this.per100g,
  );

  final String name;
  final String servingLabel;
  final double servingG;

  // 100gあたりの栄養素量。キーは nutrientSeedData のコード。
  final Map<String, double> per100g;
}

